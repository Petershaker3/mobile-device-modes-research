#!/usr/bin/env python3
"""Generate the English translation table from upstream's LocTable.*.cs files.

Why generate instead of hand-copying: upstream keeps 643 UI strings spread over
11 partial files (LocTable.MainUi.cs, LocTable.FileProxyUi.cs, ...). My first
attempt hand-picked the 19 keys the copied code seemed to need, and CI
immediately proved that guess wrong - a test failed because the key for the
payload-length error was missing, so the English lookup fell back to Chinese.
Rather than repeat that guess, this script transcribes every key from upstream
in one pass, so the table and upstream cannot drift.

Usage:
    scripts/gen-loctable.py --upstream /path/to/logcat-viewer            # write
    scripts/gen-loctable.py --upstream /path/to/logcat-viewer --check    # verify only

--check is what CI runs: it regenerates into memory and compares with the file
in the repo, so a hand edit to the generated file is caught the same way a
vendored source drift is.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

OUT = Path("src/DeviceToolkit.Core/Localization/LocTable.g.cs")

ENTRY = re.compile(r'\["((?:[^"\\]|\\.)*)"\]\s*=\s*"((?:[^"\\]|\\.)*)"')

HEADER = """// <auto-generated>
//   Generated by scripts/gen-loctable.py from upstream
//   daitouniao/logcat-viewer (Apache-2.0), logcat-uicore/Services/LocTable.*.cs
//   Do not edit by hand: CI regenerates this file and fails on any difference.
//   To change a translation, change upstream and re-run the generator.
// </auto-generated>

namespace logcat.Services;

/// <summary>
/// 英文译文表：上游 LocTable.*.cs 的完整转写（__COUNT__ 个键，0 处冲突）。
/// 键是中文原文，值是英文译文。
/// </summary>
static class LocTable
{
    public static Dictionary<string, string> All() => new()
    {
__BODY__
    };
}
"""


def collect(upstream: Path) -> tuple[dict[str, str], list[Path]]:
    src_dir = upstream / "logcat-uicore" / "Services"
    files = sorted(src_dir.glob("LocTable.*.cs"))
    if not files:
        raise SystemExit(f"no LocTable.*.cs under {src_dir}")

    table: dict[str, str] = {}
    conflicts: list[tuple[str, str, str, str]] = []
    for path in files:
        text = path.read_text(encoding="utf-8-sig")
        for key, value in ENTRY.findall(text):
            if key in table and table[key] != value:
                conflicts.append((key, table[key], value, path.name))
            table[key] = value

    if conflicts:
        # A heuristic parse that silently picks a winner would hide a real
        # disagreement between upstream files. Refuse and show them.
        for key, old, new, where in conflicts:
            print(f"  conflict {key!r}: {old!r} vs {new!r} ({where})", file=sys.stderr)
        raise SystemExit(f"{len(conflicts)} conflicting keys upstream")

    return table, files


def render(table: dict[str, str]) -> str:
    body = "\n".join(f'        ["{k}"] = "{v}",' for k, v in table.items())
    return HEADER.replace("__COUNT__", str(len(table))).replace("__BODY__", body)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", required=True, type=Path,
                    help="checkout of daitouniao/logcat-viewer")
    ap.add_argument("--check", action="store_true",
                    help="compare with the committed file instead of writing")
    args = ap.parse_args()

    table, files = collect(args.upstream)
    generated = render(table)

    if args.check:
        if not OUT.exists():
            print(f"FAIL {OUT} does not exist", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != generated:
            print(f"FAIL {OUT} differs from upstream ({len(table)} keys)", file=sys.stderr)
            return 1
        print(f"OK   LocTable.g.cs matches upstream ({len(table)} keys, {len(files)} files)")
        return 0

    OUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUT} ({len(table)} keys from {len(files)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
